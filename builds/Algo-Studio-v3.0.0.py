def ease_out_cubic(progress):
    progress = max(0.0, min(1.0, progress))
    return 1 - (1 - progress) ** 3


def ease_in_out_quad(progress):
    progress = max(0.0, min(1.0, progress))
    return 2 * progress * progress if progress < .5 else 1 - (-2 * progress + 2) ** 2 / 2


