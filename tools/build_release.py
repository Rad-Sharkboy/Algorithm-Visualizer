"""Build a readable, single-file Python release using only the standard library.

Usage: python3 tools/build_release.py --version 2.1.2
Outputs: dist/Algo-Studio-v2.1.2.py and dist/SHA256SUMS
"""

import argparse
import ast
import hashlib
from pathlib import Path
import re
import symtable

ROOT = Path(__file__).resolve().parents[1]
# Dependencies precede their consumers; PROJECT.py supplies the entry point.
MODULES = ("algorithms", "datasets", "motion", "theme", "widgets", "PROJECT")


def version_number(value):
    if not re.fullmatch(r"(?:0|[1-9]\d*)\.(?:0|[1-9]\d*)\.(?:0|[1-9]\d*)", value):
        raise argparse.ArgumentTypeError("Use a version such as 2.1.2 (without v).")
    return value


def standalone_source(version):
    sections = [f'''#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Algo Studio v{version} — Algorithms in Motion.

Run: python3 Algo-Studio-v{version}.py (Windows: py Algo-Studio-v{version}.py)
Requires Python 3.10+, Tkinter, and a graphical desktop. No pip dependencies.
All application modules are included in this file; no extraction is needed.

Source: https://github.com/Rad-Sharkboy/Algorithm-Visualizer/tree/v{version}
Generated by tools/build_release.py; edit the original modules to contribute.
"""

__version__ = "{version}"

if __name__ == "__main__":
    import sys as _release_sys
    if _release_sys.argv[1:] == ["--version"]:
        print("Algo Studio v{version}")
        raise SystemExit(0)
    if _release_sys.version_info < (3, 10):
        raise SystemExit("Algo Studio requires Python 3.10 or newer.")
''']
    bindings = {"__version__": None, "_release_sys": None}
    exports = {}
    for name in MODULES:
        path = ROOT / f"{name}.py"
        source = path.read_text(encoding="utf-8")
        lines = source.splitlines(keepends=True)
        tree = ast.parse(source, filename=path.name)
        for node in ast.walk(tree):
            if isinstance(node, ast.Import) and any(
                alias.name.split(".")[0] in MODULES for alias in node.names
            ):
                raise ValueError(f"{path.name}: use explicit 'from' imports for bundled modules")
            if not isinstance(node, ast.ImportFrom):
                continue
            if node.level or node.module == "__future__":
                raise ValueError(f"{path.name}: relative/future imports need separate handling")
            if node.module not in MODULES:
                continue
            if node not in tree.body:
                raise ValueError(f"{path.name}: bundled imports must be at module scope")
            for alias in node.names:
                if alias.asname or alias.name not in exports.get(node.module, set()):
                    raise ValueError(f"{path.name}: cannot inline {node.module}.{alias.name}")
            # AST spans also cover the theme's multiline import. Keep source readable.
            lines[node.lineno - 1:node.end_lineno] = [""] * (node.end_lineno - node.lineno + 1)
        source = "".join(lines).strip()
        table = symtable.symtable(source, path.name, "exec")
        names = {symbol.get_name() for symbol in table.get_symbols()
                 if symbol.is_assigned() or symbol.is_imported()}
        imports = {}
        for node in ast.parse(source).body:
            if isinstance(node, (ast.Import, ast.ImportFrom)):
                for alias in node.names:
                    bound = alias.asname or (alias.name.split(".")[0]
                                            if isinstance(node, ast.Import) else alias.name)
                    imports[bound] = (getattr(node, "module", None), alias.name)
        # A shared global could silently change another module's behavior. Fail the
        # build if that happens; only identical standard-library imports can repeat.
        for bound in names:
            signature = imports.get(bound)
            if bound in bindings and (signature is None or bindings[bound] != signature):
                raise ValueError(f"{path.name}: conflicting global {bound!r}")
            bindings[bound] = signature
        exports[name] = names
        sections.append(f"# {'=' * 24} {path.name} {'=' * 24}\n\n{source}\n")
    combined = "\n\n".join(sections)
    ast.parse(combined, feature_version=(3, 10))
    compile(combined, f"Algo-Studio-v{version}.py", "exec")
    return combined.encode("utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--version", required=True, type=version_number)
    parser.add_argument("--output", type=Path, default=ROOT / "dist")
    args = parser.parse_args()
    contents = standalone_source(args.version)
    output = args.output.resolve()
    output.mkdir(parents=True, exist_ok=True)
    artifact = output / f"Algo-Studio-v{args.version}.py"
    artifact.write_bytes(contents)
    digest = hashlib.sha256(contents).hexdigest()
    (output / "SHA256SUMS").write_bytes(f"{digest}  {artifact.name}\n".encode("ascii"))
    print(f"Built {artifact} ({len(contents):,} bytes)\nSHA256: {digest}")


if __name__ == "__main__":
    main()
